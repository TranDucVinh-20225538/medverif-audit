#!/usr/bin/env python3
"""Report for the Oct 1 non-reference-env cleanup chain -> notes/env_cleanup_oct1.md.

Usage: env_cleanup_report.py SNAPDIR
SNAPDIR holds pn_head.json (committed paper_numbers_final.json), pn_mid.json (after probes + Granite rescore),
a5_before.md / a5_after_granite.md (m1_strong_final_amend5.md before/after the Granite rescore), medscore_removed.json.
The current notes/paper_numbers_final.json is the final state (after the MedScore exclusion).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from table_change_list import tables  # noqa: E402

OUT = ROOT / "notes/env_cleanup_oct1.md"


def key(r: dict) -> tuple:
    return (r["table"], r["checker"], r["metric"])


def value_diff(a: list[dict], b: list[dict]) -> list[str]:
    da, db = {key(r): r for r in a}, {key(r): r for r in b}
    lines = []
    for k in list(da) + [k for k in db if k not in da]:
        ra, rb = da.get(k), db.get(k)
        va = (ra["value"], ra["n"]) if ra else ("absent", "")
        vb = (rb["value"], rb["n"]) if rb else ("absent", "")
        if va != vb:
            lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {va[0]} (n={va[1]}) | {vb[0]} (n={vb[1]}) |")
    return lines


def main() -> None:
    snap = Path(sys.argv[1])
    pn_head = json.loads((snap / "pn_head.json").read_text())
    pn_mid = json.loads((snap / "pn_mid.json").read_text())
    pn_final = json.loads((ROOT / "notes/paper_numbers_final.json").read_text())
    probes = json.loads((ROOT / "notes/env_probe_cpuverif.json").read_text())
    removed = json.loads((snap / "medscore_removed.json").read_text())
    L = ["# Non-reference-env cleanup (Oct 1 author decisions)", "",
         "Generated by `scripts/env_cleanup_report.py` in `jobs/run_env_cleanup.sbatch`.", ""]

    L += ["## 1. Bespoke-MiniCheck-7B and 3. T9 NeMo rails", "",
          "Recorded in `paper_numbers_final.md`: Bespoke `reference env = vllm (by design)`; T9 `reference env = nemo (by design)`. No probe.", ""]

    L += ["## 2. T3 / T24b reference-env probes (30 rows, seed 42)", "",
          "| file | reference env | verdicts agree | max abs score diff | result |", "|---|---|---|---:|---|"]
    for f, r in probes.items():
        if "label" not in r or f.startswith("results/raw/lane_b/"):
            continue
        res = "CHECKED" if r.get("pass") else f"failed → file rescored in {r.get('replaced_env', '?')} ({r.get('replaced_rows', 0)} rows, {r.get('replace_verdict_flips', 0)} verdict flips)"
        msd = f"{r['max_abs_score_diff']:.2e}" if r.get("max_abs_score_diff") is not None else "—"
        L.append(f"| `{f}` | {r['reference_env']} | {r['verdict_agree']}/{r['n_compared']} | {msd} | {res} |")
    L.append("")

    g = probes.get("results/raw/lane_b/m1_t7_e1_unit/t6_granite_guardian.jsonl", {})
    L += ["## 4. Granite M1 US_up: 44 cpuverif_legacy rows rescored in cpuverif", "",
          f"- Controls (cpuverif rows rescored the same way, must reproduce): {g.get('control_agree', '?')}/{len(g.get('controls', []))} verdicts, "
          f"max abs score diff {g.get('control_max_abs_score_diff', '?')}.",
          f"- Rows replaced: {g.get('replaced_rows', 0)}; verdict flips vs legacy scores: {g.get('replace_verdict_flips', 0)}. "
          f"Backup `{g.get('backup', '')}`.", ""]
    before, after = tables(snap / "a5_before.md"), tables(snap / "a5_after_granite.md")
    changes = []
    for k in list(before) + [k for k in after if k not in before]:
        a, b = before.get(k, {}), after.get(k, {})
        for col in dict.fromkeys(list(a) + list(b)):
            if a.get(col) != b.get(col):
                changes.append(f"| {k[0]} | {' · '.join(k[1:])} | {col} | {a.get(col, '—')} | {b.get(col, '—')} |")
    if changes:
        L += [f"Amendment-5 table cells that changed: **{len(changes)}**", "",
              "| section | row | column | before | after |", "|---|---|---|---|---|"] + changes + [""]
    else:
        L += ["**No cell of `results/tables/m1_strong_final_amend5.md` changed.**", ""]

    L += ["## 5. MedScore rows without API metadata excluded", "",
          f"- Removed from `results/raw/v1_medscore.jsonl`: {len(removed['ids'])} rows ({', '.join(removed['ids'])}); "
          f"backup `{removed['backup']}`.", ""]
    d5 = value_diff(pn_mid, pn_final)
    if d5:
        L += [f"Paper numbers that changed: **{len(d5)}**", "", "| table | checker | metric | before | after |",
              "|---|---|---|---|---|"] + d5 + [""]
    else:
        L += ["**No paper number changed** (values and n identical before vs after the exclusion).", ""]

    d24 = value_diff(pn_head, pn_mid)
    L += ["## Paper-number changes from steps 2 and 4 (vs committed paper_numbers_final.json)", ""]
    L += (["| table | checker | metric | before | after |", "|---|---|---|---|---|"] + d24 + [""]) if d24 else ["None.", ""]

    L += ["## 7. Token-overlap exploratory on amendment-5 texts", "",
          "`notes/m1_token_overlap_exploratory_amend5.md` (pre-amendment-5 version kept as `notes/m1_token_overlap_exploratory.md`).", ""]

    unchecked = [r for r in pn_final if r["status"] == "UNCHECKED"]
    from collections import Counter
    st = Counter(r["status"] for r in pn_final)
    L += ["## 8. paper_numbers_final.md after 1–7", "",
          f"- {len(pn_final)} numbers: " + ", ".join(f"{k} {v}" for k, v in st.most_common()), ""]
    if unchecked:
        L += [f"Remaining UNCHECKED: **{len(unchecked)}**", "", "| table | checker | metric | non-reference file(s) without a check | env of those rows |",
              "|---|---|---|---|---|"]
        for r in unchecked:
            files = r["unchecked_non_reference_files"]
            L.append(f"| {r['table']} | {r['checker']} | {r['metric']} | {', '.join(f'`{f}`' for f in files)} | {r['env']} |")
        L.append("")
    else:
        L += ["**Remaining UNCHECKED: 0.**", ""]
    OUT.write_text("\n".join(L) + "\n")
    print("\n".join(L[:6]))
    print(json.dumps({"unchecked": len(unchecked), "medscore_changes": len(d5), "a5_cell_changes": len(changes), "step24_changes": len(d24)}))


if __name__ == "__main__":
    main()
