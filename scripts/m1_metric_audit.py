#!/usr/bin/env python3
"""Cell-level metric audit for results/tables/m1_before_after.md → reconcile notes."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "analysis"))
sys.path.insert(0, str(ROOT / "scripts"))

from analyze import (  # noqa: E402
    _c0_pass_bases,
    _parsed,
    bootstrap_rate,
    load_joined_from_records,
    read_jsonl,
    sensitivity_invariance,
)
from m1_before_after_report import (  # noqa: E402
    INST,
    RAW,
    RAW_M1,
    VERIFIERS,
    _group_by_base,
    paired_inv,
    slice_table,
)
from review_filters import analysis_keep_row  # noqa: E402

RECONCILE = ROOT / "notes" / "reconcile_llama70b_qi.md"
MARKER = "## M1 before/after table — per-cell audit"


def _slice_stats(rows: list[dict], verifier: str, tag: str) -> dict:
    block = [r for r in rows if r["verifier"] == verifier and analysis_keep_row(r)]
    cond = _c0_pass_bases(block)
    inv_rows = [
        r
        for r in block
        if r["base_id"] in cond and r["condition"] == "INV-claim" and _parsed(r)
    ]
    e1_rows = [
        r
        for r in block
        if r["base_id"] in cond and r["condition"] == "E1-evid" and _parsed(r)
    ]
    c0_rows = [r for r in block if r["condition"] == "C0" and _parsed(r)]
    inv = bootstrap_rate(
        [
            (sum(1 for r in g if r["verdict"] == "PASS"), len(g))
            for _, g in _group_by_base(inv_rows).items()
        ]
    )
    e1 = bootstrap_rate(
        [
            (sum(1 for r in g if r["verdict"] == "FAIL"), len(g))
            for _, g in _group_by_base(e1_rows).items()
        ]
    )
    c0 = bootstrap_rate(
        [
            (sum(1 for r in g if r["verdict"] == "PASS"), len(g))
            for _, g in _group_by_base(c0_rows).items()
        ]
    )
    score_key = {
        "v2a_minicheck": "results/raw/v2a_minicheck.jsonl",
        "v3_alignscore": "results/raw/v3_alignscore.jsonl",
        "v1_medscore": "results/raw/v1_medscore.jsonl",
        "v4_ragas_nli": "results/raw/v4_ragas_nli.llama.jsonl",
    }[verifier]
    if tag == "M1":
        score_key = score_key.replace("results/raw/", "results/raw_m1/")
    return {
        "tag": tag,
        "verifier": verifier,
        "instances": str(INST.relative_to(ROOT)),
        "scores": score_key,
        "exclusions": "analysis_keep_row; valid instances only",
        "conditioning": "C0 PASS bases from same verifier+DOSE block",
        "c0": c0,
        "qi": inv,
        "ns": e1,
        "n_c0_bases": len(cond),
    }


def audit_markdown() -> str:
    instances = [r for r in read_jsonl(INST) if r.get("valid", True)]
    raw = load_joined_from_records(instances, RAW)
    m1 = load_joined_from_records(instances, RAW_M1) if RAW_M1.is_dir() else []

    lines = [
        MARKER,
        "",
        f"Generated by `scripts/m1_metric_audit.py`. Instances `{INST.relative_to(ROOT)}` "
        f"(n={len(instances)}). Cluster-bootstrap by `base_id` (seed 42).",
        "",
        "### Column semantics (correct labels)",
        "",
        "| Column | Metric | Definition |",
        "| --- | --- | --- |",
        "| C0 pass | **C0** (baseline support) | Micro PASS rate on **C0** rows (parsed), cluster-bootstrap by base |",
        "| INV pass (\\|C0) | **QI** | PASS rate on **INV-claim** (all magnitudes: unit, rephrase, …), \\| C0 PASS, parsed |",
        "| E1-evid FAIL (\\|C0) | **NS** | FAIL rate on **E1-evid** (evidence dose perturbation), \\| C0 PASS — **not QI** |",
        "",
        "**Common error:** citing **NS (~87–93%)** or **QI (~85%)** as Llama-70B QI. "
        "Paper Llama QI = **natural INV-unit only** (see rows A–F above). "
        "M1 **V4 raw QI 84.9%** is **Qwen** `v4_ragas_nli.jsonl`, not Llama.",
        "",
        "### Main table cells",
        "",
        "| Row | Metric | Subset | Conditioning | n (num/den) | Rate | Source scores |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]

    vkey_to_label = dict(VERIFIERS)
    for vkey, vlabel in VERIFIERS:
        if not any(r["verifier"] == vkey for r in raw):
            continue
        for tag, rows in (("raw", raw), ("M1", m1)):
            if tag == "M1" and not m1:
                continue
            st = _slice_stats(rows, vkey, tag)
            for metric, key, subset in (
                ("C0", "c0", "C0 all"),
                ("QI", "qi", "INV-claim all magnitudes"),
                ("NS", "ns", "E1-evid"),
            ):
                cell = st[key]
                rate = cell["rate"]
                rate_s = "NA" if rate is None else f"{rate:.3f}"
                ci = ""
                if cell.get("lo") is not None:
                    ci = f" [{cell['lo']:.3f},{cell['hi']:.3f}]"
                lines.append(
                    f"| {vlabel} {tag} | **{metric}** | {subset} | \\| C0 PASS ({st['n_c0_bases']} bases) | "
                    f"{cell['num']}/{cell['den']} | {rate_s}{ci} | `{st['scores']}` |"
                )

    lines += [
        "",
        "### DOSE macro (`sensitivity_invariance`)",
        "",
        "| Verifier | tag | Metric | Value | Notes |",
        "| --- | --- | --- | ---: | --- |",
    ]
    si_raw = {v: sensitivity_invariance(raw) for v, _ in VERIFIERS}
    si_m1 = {v: sensitivity_invariance(m1) for v, _ in VERIFIERS} if m1 else {}
    for vkey, vlabel in VERIFIERS:
        pr = next((p for p in si_raw.get(vkey, []) if p["type"] == "DOSE"), {})
        if pr:
            lines.append(
                f"| {vlabel} | raw | **QI** (invariance) | {pr.get('invariance')} | "
                "INV-claim PASS \\| C0; macro DOSE |"
            )
            lines.append(
                f"| {vlabel} | raw | **NS** (sensitivity_e1_evid) | {pr.get('sensitivity_e1_evid')} | "
                "E1-evid FAIL \\| C0; macro DOSE |"
            )
        if si_m1:
            pm = next((p for p in si_m1.get(vkey, []) if p["type"] == "DOSE"), {})
            if pm:
                lines.append(
                    f"| {vlabel} | M1 | **QI** | {pm.get('invariance')} | post-M1 scores |"
                )
                lines.append(
                    f"| {vlabel} | M1 | **NS** | {pm.get('sensitivity_e1_evid')} | post-M1 scores |"
                )

    if m1:
        lines += ["", "### McNemar (QI discordance, INV-claim \\| C0)", ""]
        for vkey, vlabel in VERIFIERS:
            if not any(r["verifier"] == vkey for r in raw):
                continue
            mc = paired_inv(raw, m1, vkey)
            lines.append(
                f"- **{vlabel}:** raw→M1 pass→fail b={mc['discordant_pass_fail']}, "
                f"fail→pass c={mc['discordant_fail_pass']} (INV-claim \\| C0, parsed)"
            )

    lines += [
        "",
        "### paper_numbers (`qvc/paper_numbers.json`)",
        "",
    ]
    pn_path = ROOT / "qvc/paper_numbers.json"
    if pn_path.is_file():
        pn = json.loads(pn_path.read_text())
        lines.append(f"- Source: `{pn_path.relative_to(ROOT)}`, n_joined={pn.get('n_joined')}.")
        lines.append(
            "- `rate_table_subset` uses **analyze.rate_table** on cpu_early — "
            "conditions are **not** labeled QI/NS in JSON; map C0→C0, INV→QI, E1→NS when citing."
        )
    else:
        lines.append(
            "- No committed draft at `qvc/paper_numbers.json` "
            "(regenerate with `python scripts/qvc_reproduce_paper_numbers.py` when needed)."
        )

    lines += [
        "",
        "### Numeric changes from this audit",
        "",
        "- See manual notes in this section of `notes/reconcile_llama70b_qi.md` "
        "(regenerate may shift rows if raw score files change; V1 raw QI was sensitive).",
        "",
    ]
    return "\n".join(lines)


def patch_reconcile(md: str) -> None:
    text = RECONCILE.read_text() if RECONCILE.is_file() else ""
    if MARKER in text:
        head = text.split(MARKER)[0].rstrip()
        new_text = head + "\n\n" + md.strip() + "\n"
    else:
        new_text = text.rstrip() + "\n\n" + md.strip() + "\n"
    RECONCILE.write_text(new_text)


def main() -> None:
    md = audit_markdown()
    patch_reconcile(md)
    print(RECONCILE)


if __name__ == "__main__":
    main()
